import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {startVitest} from 'vitest/node';
import {loadConfigFromFile} from 'vite';
const evidence=process.env['MALPACO_DEV_WATCH_EVIDENCE'] || path.dirname(fileURLToPath(import.meta.url));
const stamp=new Date().toISOString().replaceAll(':','-');
const root=path.resolve('.cache/issue187-vitest',stamp);
const testFile=path.join(root,'tests/watch.test.ts');
await mkdir(path.dirname(testFile),{recursive:true});
await mkdir(path.join(root,'.cache/retained'),{recursive:true});
await writeFile(path.join(root,'.cache/retained/noise.ts'),'export const noise=1;');
const body=n=>`import {test,expect} from 'vitest'; test('watch ${n}',()=>expect(${n}).toBe(${n}));\n`;
await writeFile(testFile,body(1));
const proposed=await loadConfigFromFile({command:'serve',mode:'test'},path.resolve('vite.config.ts'));
assert.deepEqual(proposed.config.server.watch.ignored,[path.resolve('.cache')]);
const records=[];
let ctx;
try {
  ctx=await startVitest([], {root,config:false,watch:true,include:['tests/**/*.test.ts'],maxWorkers:1,reporters:[{onTestRunEnd(modules,errors,reason){records.push({reason,errors:errors.length,modules:modules.map(m=>({file:path.relative(root,m.moduleId),state:m.state()}))});}}]}, {server:{watch:{ignored:[path.join(root,'.cache')]}}});
  await writeFile(testFile,body(2));
  const deadline=Date.now()+10000;
  while(records.length<2&&Date.now()<deadline) await new Promise(r=>setTimeout(r,100));
  const watched=Object.keys(ctx.vite.watcher.getWatched()).map(p=>path.relative(root,p));
  const output={root,records,watched};
  await writeFile(path.join(evidence,`vitest-${stamp}.json`),JSON.stringify(output,null,2)+'\n');
  assert(records.length>=2,'test edit must trigger a second test run');
  assert(records.every(r=>r.errors===0&&r.modules.every(m=>m.state==='passed')));
  assert(!watched.some(p=>p==='.cache'||p.startsWith('.cache/')));
  assert(watched.includes('tests'));
  console.log(JSON.stringify(output));
} finally {await ctx?.close();}
